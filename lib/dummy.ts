export type Role = "admin" | "manager" | "cashier";

export interface Category {
  id: string;
  name: string;
  slug: string;
}

export interface Variant {
  id: string;
  sku: string;
  name: string;
  size: string;
  color: string;
  colorCode: string;
  sellingPrice: number;
  costPrice: number;
  barcode?: string;
}

export interface Product {
  id: string;
  sku: string;
  name: string;
  description: string;
  categoryId: string;
  images: string[];
  tags: string[];
  active: boolean;
  stock: number;
  variants: Variant[];
  fabric: string;
  care: string;
  season?: string;
  brand?: string;
  compareAt?: number;
}

export interface Customer {
  id: string;
  name: string;
  phone: string;
  totalPurchases: number;
  visitCount: number;
  email?: string;
  address?: string;
  birthday?: string;
  notes?: string;
  tags?: string[];
}

export type PaymentMethod = "qris" | "cash" | "transfer" | "shopee";
export type TransactionStatus = "pending" | "paid" | "cancelled" | "refunded";

export interface TransactionItem {
  productId: string;
  variantId: string;
  name: string;
  sku: string;
  size: string;
  color: string;
  quantity: number;
  unitPrice: number;
  costPrice: number;
  discount: number;
  total: number;
}

export interface Transaction {
  id: string;
  number: string;
  cashier: string;
  customerId?: string;
  customerName?: string;
  status: TransactionStatus;
  paymentMethod: PaymentMethod;
  paymentStatus: "pending" | "paid" | "failed" | "expired";
  subtotal: number;
  tax: number;
  discount: number;
  total: number;
  amountPaid: number;
  change: number;
  items: TransactionItem[];
  createdAt: string;
  qrisRef?: string;
  photoProof?: string;
}

export interface Shift {
  id: string;
  staff_name: string;
  opened_at: string;
  closed_at?: string;
  startingCash: number;
  endingCash?: number;
  totalTransactions: number;
  totalSales: number;
  totalQris: number;
  totalCash: number;
  status: "open" | "closed" | "reconciled";
}

